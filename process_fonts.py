import math
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FIRST_CHAR = 32
LAST_CHAR = 126

# The fonts also carry these, after the ASCII characters.
EXTRA_CHARS = "£"

build_dir = Path("app") / "font"
build_dir.mkdir(exist_ok=True)


def render_font_ttb_ltr(ttf_path: Path, font_size: int, padding: int = 1):
    font = ImageFont.truetype(ttf_path, font_size)

    # Determine max glyph height
    ascent, descent = font.getmetrics()
    height = ascent + descent
    rows = height + padding * 2
    rows_bytes = math.ceil(rows / 8)

    font_table = {}

    for ch in [chr(code) for code in range(FIRST_CHAR, LAST_CHAR + 1)] + list(EXTRA_CHARS):
        # Measure glyph
        bbox = font.getbbox(ch)
        if bbox is None:
            continue

        w = bbox[2] - bbox[0]
        cols = w + padding * 2

        # Create 1-bit image
        img = Image.new("1", (cols, rows), 1)
        draw = ImageDraw.Draw(img)

        draw.text((padding - bbox[0], padding), ch, font=font, fill=0)

        pixels = img.load()

        glyph = []

        for x in range(cols):
            col_bytes = bytearray(rows_bytes).replace(b"\x00", b"\xff")

            for y in range(rows):
                if pixels[x, y] == 0:
                    byte_index = y // 8
                    bit_index = 7 - (y % 8)
                    col_bytes[byte_index] &= ~(1 << bit_index)

            glyph.append(col_bytes)

        font_table[ch] = glyph

    return font_table, rows, rows_bytes


def create_font_file(name, source_path, size):
    font_table, height_px, height_bytes = render_font_ttb_ltr(source_path, font_size=size, padding=0)
    create_packed_file(name, font_table, height_bytes)


def create_packed_file(name, font_table, height_bytes):
    """
    A font as two bytes objects, which takes about 3 KB of the ESP32's RAM (a dict of lists takes about 35 KB).

    ROWS: bytes per column. DATA: every glyph's columns one after another, top pixel in the most
    significant bit, 0 = black. INDEX: where each glyph starts in DATA, counted in columns, two bytes each (low byte
    first), in the order ASCII 32-126 then EXTRA_CHARS, with one more entry marking the end.
    """
    index = bytearray()
    data = bytearray()
    for ch in [chr(code) for code in range(FIRST_CHAR, LAST_CHAR + 1)] + list(EXTRA_CHARS):
        index += (len(data) // height_bytes).to_bytes(2, "little")
        for col in font_table[ch]:
            data += col
    index += (len(data) // height_bytes).to_bytes(2, "little")

    with (build_dir / f"packed_{name}.py").open("w") as f:
        print("# Generated by process_fonts.py", file=f)
        print(f"ROWS = {height_bytes}", file=f)
        print(f"INDEX = {bytes(index)!r}", file=f)
        print(f"DATA = {bytes(data)!r}", file=f)


def path_to_module_name(path: Path):
    return re.sub(r"\W|^(?=\d)", "_", path.stem.lower())


if __name__ == "__main__":
    # The fonts the reader program draws with (app/screen.py).
    manifest = [
        ("ari/ari-w9500-condensed-display.ttf", 16),
        ("ari/ari-w9500-condensed-bold.ttf", 16),
    ]

    for filename, size in manifest:
        p = Path(filename)
        create_font_file(path_to_module_name(p), Path("font") / filename, size)
